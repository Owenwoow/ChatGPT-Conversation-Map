const {expect} = require('@playwright/test');

module.exports = async function notebookScenario(context, popup) {
  const route = '/c/notebook-test';
  const page = await context.newPage();
  const root = page.locator('#dual-navigator-host');
  await page.goto('https://chatgpt.com' + route);
  await expect(root.locator('.tick')).toHaveCount(8);
  await expect(root.locator('.mm-open')).toHaveCount(0);
  await page.evaluate(() => {
    const form = document.createElement('form');
    form.setAttribute('data-chatgpt-composer', '');
    form.innerHTML = '<div contenteditable="true" data-composer-markdown role="textbox" style="min-height:24px;white-space:pre-wrap"></div><button type="submit" aria-label="发送">发送</button>';
    document.querySelector('.composer .input').replaceChildren(form);
    let index = 8;
    form.onsubmit = event => {
      event.preventDefault();
      if (form.dataset.fail) return;
      const input = form.querySelector('[contenteditable]');
      const answer = addTurn(index++);
      answer.previousElementSibling.querySelector('[data-message-id]').textContent = input.innerText;
      input.replaceChildren();
    };
  });
  const editor = page.locator('[data-composer-markdown]');
  await editor.fill('这是我已经写好的草稿。');
  const annotate = async (id, question) => {
    await page.evaluate(id => {
      const p = document.querySelector('[data-message-id="' + id + '"] p');
      p.scrollIntoView({block:'center'});
      const range = document.createRange();
      range.selectNodeContents(p);
      const selection = document.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
    }, id);
    await root.getByRole('textbox', {name:'想追问的问题'}).fill(question);
    await root.getByRole('button', {name:'保存注释'}).click();
    await expect(root.locator('.dn-annotate')).toBeHidden();
  };
  await annotate('a0', '这段怎么实际应用？');
  await annotate('a1', '举个例子。');
  await root.getByRole('button', {name:'2 条注释'}).click();
  await root.getByRole('button', {name:'编辑', exact:true}).last().click();
  await root.getByRole('textbox', {name:'想追问的问题'}).fill('有没有其他例子？');
  await root.getByRole('button', {name:'保存注释'}).click();
  await expect(root.getByRole('button', {name:'2 条注释'})).toBeVisible();
  await expect(root.getByRole('region', {name:'待发送注释'})).toBeHidden();
  await expect(editor).toHaveText('这是我已经写好的草稿。');
  const chipBounds = await root.locator('.dn-annotation-chip').boundingBox();
  const composerBounds = await page.locator('form[data-chatgpt-composer]').boundingBox();
  expect(chipBounds.y + chipBounds.height).toBeLessThanOrEqual(composerBounds.y);

  await page.bringToFront();
  const [notebook] = await Promise.all([context.waitForEvent('page'), popup.locator('#openNotebook').click()]);
  await expect(notebook.locator('#turns li')).toHaveCount(8);
  await expect(notebook.locator('#clips li')).toHaveCount(2);
  await notebook.locator('#turns li').first().dragTo(notebook.locator('#viewport'), {targetPosition:{x:350,y:280}});
  await expect(notebook.locator('[data-card="u0"]')).toBeVisible();
  await notebook.locator('#clips li').first().getByRole('button', {name:'加入画布'}).click();
  await expect(notebook.locator('#cards .node')).toHaveCount(2);
  await notebook.locator('#connect').click();
  await notebook.locator('[data-card="u0"]').click();
  await expect(notebook.locator('#links path')).toHaveCount(1);
  await notebook.locator('#close-details').click();
  await notebook.locator('#fit-view').click();
  const first = notebook.locator('[data-card="u0"]');
  const before = await first.evaluate(card => card.style.left);
  const start = await first.boundingBox();
  await notebook.mouse.move(start.x + 24, start.y + 28);
  await notebook.mouse.down();
  await notebook.mouse.move(start.x + 116, start.y + 36, {steps:4});
  await notebook.mouse.up();
  await expect.poll(() => first.evaluate(card => card.style.left)).not.toBe(before);
  await notebook.locator('#new-group').click();
  await notebook.locator('#close-details').click();
  await notebook.locator('#fit-view').click();
  const clip = notebook.locator('[data-card^="clip-"]');
  const source = await clip.boundingBox(), group = await notebook.locator('[data-group]').boundingBox();
  await notebook.mouse.move(source.x + source.width / 2, source.y + source.height / 2);
  await notebook.mouse.down();
  await notebook.mouse.move(group.x + group.width / 2, group.y + group.height / 2, {steps:6});
  await notebook.mouse.up();
  await expect(notebook.locator('[data-group] small')).toHaveText('1');
  await notebook.locator('#fold-groups').click();
  await expect(clip).toHaveCount(0);
  await expect(notebook.locator('#links path')).toHaveCount(1);
  await notebook.locator('#start-view').click();
  await expect(first).toHaveClass(/start/);

  await page.bringToFront();
  await root.getByRole('button', {name:'2 条注释'}).click();
  await root.getByRole('button', {name:'合并到输入框'}).click();
  await expect(editor).toContainText('这是我已经写好的草稿。');
  await expect(editor).toContainText('问题：这段怎么实际应用？');
  await expect(editor).toContainText('问题：有没有其他例子？');
  await root.getByRole('button', {name:'2 条注释'}).click();
  await root.getByRole('button', {name:'合并到输入框'}).click();
  expect((await editor.innerText()).match(/【引用与问题】/g)).toHaveLength(1);
  await page.locator('form[data-chatgpt-composer]').evaluate(form => form.dataset.fail = '1');
  await page.getByRole('button', {name:'发送', exact:true}).click();
  await expect(root.getByRole('button', {name:'2 条注释'})).toBeVisible();
  await page.locator('form[data-chatgpt-composer]').evaluate(form => delete form.dataset.fail);
  await page.getByRole('button', {name:'发送', exact:true}).click();
  await expect(page.locator('[data-message-id="u8"]')).toContainText('问题：有没有其他例子？');
  await expect(root.locator('.dn-annotation-chip')).toBeHidden();
  await expect(notebook.locator('#clips li')).toHaveCount(0);
  await notebook.close();
  await page.close();

  await popup.reload();
  const [reopened] = await Promise.all([context.waitForEvent('page'), popup.locator('#recentMapLinks a').first().click()]);
  await expect(reopened.locator('[data-card="u0"]')).toBeVisible();
  await expect(reopened.locator('[data-group] small')).toHaveText('1');
  await reopened.locator('[data-group] .topic-toggle').click();
  await expect(reopened.locator('[data-card^="clip-"]')).toBeVisible();
  await reopened.locator('[data-card^="clip-"]').click();
  await expect(reopened.locator('#excerpt')).toContainText('我们从日常使用网络');
  const [original] = await Promise.all([context.waitForEvent('page'), reopened.locator('#go-to-source').click()]);
  await expect(original.locator('#dual-navigator-host .tick').first()).toHaveAttribute('aria-current', 'step');
  await expect(original).toHaveURL('https://chatgpt.com' + route);
  await reopened.close();
  await original.close();
  console.log('PASS 注释收集与组合发送、失败保留、独立笔记本拖放和归组、恢复及返回原文');
};
